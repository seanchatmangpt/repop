def rows_with_envelope(individual, rows):
    """layout_spec pins each table to DIGEST_OFFSET=60 with the FNV-1a32
    digest at 60..64 (envelope-law consts). For IntentFrame/HyperplaneRegister
    the digest is an envelope row appended to the pinned table; for
    ReceiptFrame it is the pinned table's own last row."""
    if any(r[1] == DIGEST_OFFSET for r in rows):
        return rows
    return rows + [("digest", DIGEST_OFFSET, 4, "wkU32LE", None)]

