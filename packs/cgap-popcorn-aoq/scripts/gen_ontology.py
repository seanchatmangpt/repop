import sys

HEX = lambda h: int(h, 16)
BAND_LO, BAND_HI = HEX("0x5250A001"), HEX("0x5250A009")
ALG_BLAKE3, ALG_MLDSA = HEX("0x0000"), HEX("0x0001")
