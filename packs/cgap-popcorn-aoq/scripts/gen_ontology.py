    w(f"cp:{name} a owl:Class ;")
    w(f"    owl:oneOf ( {' '.join('cp:'+m for m, _ in members)} ) ;")
    w(f'    rdfs:label "{label} - closed enum" .')
    for m, val in members:
        w(f"cp:{m} a cp:{name} ; cp:value {val} .")
    w("")

